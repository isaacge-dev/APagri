-- =============================================================================
-- SECTION 2: TRIGGER FUNCTIONS
-- =============================================================================

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;


-- =============================================================================
-- SECTION 3: 3NF LOOKUP & REFERENCE TABLES (Parent Lookups)
-- =============================================================================

-- 3.1 Harvest Remarks Lookup Table (Rubric Requirement)
CREATE TABLE public.harvest_remark (
    remark_id INT PRIMARY KEY,
    remark_description VARCHAR(80) NOT NULL
);

-- 3.2 Soil Types Lookup Table
CREATE TABLE public.soil_type_lookup (
    soil_type_id SERIAL PRIMARY KEY,
    soil_name VARCHAR(50) UNIQUE NOT NULL,
    description TEXT
);

-- 3.3 Irrigation Types Lookup Table
CREATE TABLE public.irrigation_type_lookup (
    irrigation_type_id SERIAL PRIMARY KEY,
    irrigation_name VARCHAR(50) UNIQUE NOT NULL,
    description TEXT
);

-- 3.4 Crop Categories Lookup Table
CREATE TABLE public.crop_category_lookup (
    category_id SERIAL PRIMARY KEY,
    category_name VARCHAR(50) UNIQUE NOT NULL
);

-- 3.5 Recommended Seasons Lookup Table
CREATE TABLE public.season_lookup (
    season_id SERIAL PRIMARY KEY,
    season_name VARCHAR(50) UNIQUE NOT NULL
);

-- 3.6 Planting Statuses Lookup Table
CREATE TABLE public.planting_status_lookup (
    status_id SERIAL PRIMARY KEY,
    status_code VARCHAR(30) UNIQUE NOT NULL,
    status_label VARCHAR(50) NOT NULL
);

-- 3.7 Quality Grades Lookup Table
CREATE TABLE public.quality_grade_lookup (
    grade_code VARCHAR(10) PRIMARY KEY,
    grade_label VARCHAR(50) NOT NULL,
    description TEXT
);


-- =============================================================================
-- SECTION 4: CORE ENTITIES & RELATIONAL MODULES (With Foreign Keys)
-- =============================================================================

-- 4.1 Farmer Table
CREATE TABLE public.farmer (
    farmer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    contact_number VARCHAR(20),
    address VARCHAR(150),
    date_registered DATE DEFAULT CURRENT_DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    deleted_by VARCHAR(100) NULL DEFAULT NULL
);

-- 4.2 Farm Table (Connected to farmer, soil_type_lookup, irrigation_type_lookup)
CREATE TABLE public.farm (
    farm_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id INT NOT NULL,
    farm_name VARCHAR(100) NOT NULL,
    location VARCHAR(150),
    area_hectares NUMERIC(8,2) NOT NULL,
    soil_type_id INT,
    irrigation_type_id INT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    deleted_by VARCHAR(100) NULL DEFAULT NULL,

    -- Foreign Keys
    CONSTRAINT fk_farm_farmer FOREIGN KEY (farmer_id)
        REFERENCES public.farmer(farmer_id) ON DELETE CASCADE,
    CONSTRAINT fk_farm_soil_type FOREIGN KEY (soil_type_id)
        REFERENCES public.soil_type_lookup(soil_type_id) ON DELETE SET NULL,
    CONSTRAINT fk_farm_irrigation_type FOREIGN KEY (irrigation_type_id)
        REFERENCES public.irrigation_type_lookup(irrigation_type_id) ON DELETE SET NULL,

    -- Integrity Check
    CONSTRAINT chk_farm_area_positive CHECK (area_hectares > 0)
);

-- 4.3 Crop Table (Connected to crop_category_lookup, season_lookup)
CREATE TABLE public.crop (
    crop_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_name VARCHAR(80) NOT NULL,
    variety VARCHAR(80),
    category_id INT,
    growing_period_days INT NOT NULL,
    season_id INT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    deleted_by VARCHAR(100) NULL DEFAULT NULL,

    -- Foreign Keys
    CONSTRAINT fk_crop_category FOREIGN KEY (category_id)
        REFERENCES public.crop_category_lookup(category_id) ON DELETE SET NULL,
    CONSTRAINT fk_crop_season FOREIGN KEY (season_id)
        REFERENCES public.season_lookup(season_id) ON DELETE SET NULL,

    -- Integrity Checks
    CONSTRAINT uq_crop_name_variety UNIQUE (crop_name, variety),
    CONSTRAINT chk_crop_period_positive CHECK (growing_period_days > 0)
);

-- 4.4 Planting Table (Connected to farm, crop, planting_status_lookup)
CREATE TABLE public.planting (
    planting_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id INT NOT NULL,
    crop_id INT NOT NULL,
    planting_date DATE NOT NULL,
    area_planted NUMERIC(8,2) NOT NULL,
    seed_quantity NUMERIC(8,2) NOT NULL DEFAULT 0.00,
    expected_harvest_date DATE,
    status_id INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    deleted_by VARCHAR(100) NULL DEFAULT NULL,

    -- Foreign Keys
    CONSTRAINT fk_planting_farm FOREIGN KEY (farm_id)
        REFERENCES public.farm(farm_id) ON DELETE CASCADE,
    CONSTRAINT fk_planting_crop FOREIGN KEY (crop_id)
        REFERENCES public.crop(crop_id) ON DELETE CASCADE,
    CONSTRAINT fk_planting_status FOREIGN KEY (status_id)
        REFERENCES public.planting_status_lookup(status_id) ON DELETE RESTRICT,

    -- Integrity Checks
    CONSTRAINT chk_planting_area_positive CHECK (area_planted > 0),
    CONSTRAINT chk_planting_seed_nonneg CHECK (seed_quantity >= 0),
    CONSTRAINT chk_planting_dates CHECK (expected_harvest_date IS NULL OR expected_harvest_date >= planting_date)
);

-- 4.5 Harvest Table (Connected to planting, harvest_remark, quality_grade_lookup)
CREATE TABLE public.harvest (
    harvest_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planting_id INT NOT NULL,
    harvest_date DATE NOT NULL,
    quantity_kg NUMERIC(10,2) NOT NULL,
    selling_price_per_kg NUMERIC(10,2) DEFAULT NULL,
    quality_grade VARCHAR(10),
    remark_id INT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP NULL DEFAULT NULL,
    deleted_by VARCHAR(100) NULL DEFAULT NULL,

    -- Foreign Keys
    CONSTRAINT fk_harvest_planting FOREIGN KEY (planting_id)
        REFERENCES public.planting(planting_id) ON DELETE CASCADE,
    CONSTRAINT fk_harvest_quality_grade FOREIGN KEY (quality_grade)
        REFERENCES public.quality_grade_lookup(grade_code) ON DELETE SET NULL,
    CONSTRAINT fk_harvest_remark FOREIGN KEY (remark_id)
        REFERENCES public.harvest_remark(remark_id) ON DELETE SET NULL,

    -- Integrity Checks
    CONSTRAINT chk_harvest_qty_positive CHECK (quantity_kg > 0),
    CONSTRAINT chk_harvest_price_nonneg CHECK (selling_price_per_kg IS NULL OR selling_price_per_kg >= 0)
);


-- =============================================================================
-- SECTION 5: AUTHENTICATION, AUTHORIZATION & AUDIT SYSTEM
-- =============================================================================

-- 5.1 Users Table
CREATE TABLE public.users (
    user_id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    username VARCHAR(80) UNIQUE NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('Administrator', 'Staff')),
    permissions JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5.2 Activity Logs Table (Connected to users)
CREATE TABLE public.activity_logs (
    log_id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id INT,
    user_name VARCHAR(120) NOT NULL,
    action_type VARCHAR(40) NOT NULL,
    module_name VARCHAR(80) NOT NULL,
    record_id VARCHAR(80),
    description TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Foreign Key
    CONSTRAINT fk_activity_logs_user FOREIGN KEY (user_id)
        REFERENCES public.users(user_id) ON DELETE SET NULL
);


